// ADR 0012 §2 provenance-reconciliation resolver: the five citation forms and
// four degradation rules that join `interaction-design.md` information items
// and UI states against `contracts/api/api-contract.md` (+ its ADR 0007
// `openapi.json` projection) and `contracts/data/data-shape-contract.md`. See
// docs/adr/0012-interaction-design-loop.md §2 and
// contracts/ci/ci-gate-contract.md `## Provenance Reconciliation Policy` for
// the binding spec; this module implements it, it does not restate it.
//
// Reuse discipline (do NOT re-derive the ADR 0007 projection):
//  - Field-existence / enum-pin citations resolve against the COMMITTED
//    contracts/api/openapi.json, generated by src/commands/openapi-export.ts.
//    Freshness is checked with that same module's own `--check` comparison
//    (openapiExport({ check: true })) -- never a separate staleness check.
//  - Bare-status / errors-column / implicit-status citations resolve directly
//    against the parsed endpoint table (src/contracts/parser.ts
//    `parseEndpoints`) and do NOT need openapi.json at all (ADR 0012 §2: "do
//    NOT require the projection ... stay checkable when ## Schemas is
//    empty").
//  - `contracts/api/api-contract.md` / `contracts/data/data-shape-contract.md`
//    applicability markers are read with `projectApplicability` (parser.ts) --
//    the SAME read-only reader `cdd-kit doctor` already uses to DISPLAY other
//    contracts' markers. This is not a second pass/fail authority for the ADR
//    0011 marker on `interaction-design.md` itself (that stays applicability.py
//    exclusively, see gate-design.ts); it is this resolver's OWN, ADR-0012-
//    specific consumption of a target contract's marker as data, to produce
//    the "citing a family the project declared it does not have" HARD
//    category (ci-gate-contract.md `## Provenance Reconciliation Policy`).

